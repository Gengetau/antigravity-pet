"""Facial-expression variants of each form's idle frame.

Only the face changes: every expression is generated by editing the idle
frame, then just the face region (a feathered ellipse) is aligned and pasted
back onto that same idle frame.  Hair, body and outline therefore stay
pixel-identical, so switching expressions never makes the sprite jump.

    py -3.13 tools/sprite_gen/expressions.py gen --form claude [--only happy,shy]
    py -3.13 tools/sprite_gen/expressions.py composite --form claude
    py -3.13 tools/sprite_gen/expressions.py install --form claude
    py -3.13 tools/sprite_gen/expressions.py sheet

Outputs: art_work/<form>/expr/raw/<name>.png (generated),
art_work/<form>/expr/composite/<name>.png (full-size composite),
<form>/processed/runtime/expressions/<name>_<h>.png plus an ``expressions``
section in <form>/manifests/actions.json.
"""

