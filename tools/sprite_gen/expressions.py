# Face ellipse (centre x, centre y, radius x, radius y) in the 1024x1536 idle
# frame.  Covers eyes, brows, cheeks and mouth; bangs above stay from the base.
FACE_BOX = {
    "carbon": (476, 478, 176, 112),
    "hydergon": (466, 466, 166, 108),
    "neon": (490, 486, 176, 112),
    "claude": (476, 470, 166, 108),
    "argon": (495, 535, 165, 95),
}


def face_for(form: str, name: str) -> str:
    return FORM_FACES.get(form, {}).get(name, BASE_FACES[name])


def base_frame(form: str) -> Path:
    """The idle frame that is actually played (seed dropped, first kept)."""
    raws = sorted((WORK / form / "raw" / "idle_front").glob("*.png"))
    if len(raws) < 2:
        sys.exit(f"{form}：找不到待机帧 art_work/{form}/raw/idle_front/01.png")
    return raws[1]


def _gen_one(form: str, name: str, quality: str) -> Path:
    out = WORK / form / "expr" / "raw" / f"{name}.png"
    if out.is_file():
        return out
    prompt = (
        "Edit this exact image. Change ONLY her facial expression (eyes, eyebrows, mouth and cheek blush) to: "
        f"{face_for(form, name)}. "
        "Keep the face position, head size and angle, hair, bangs, ears, accessories, body, outfit, pose, framing and scale "
        "exactly identical to the input image. Same art style and line quality. Make the expression clearly readable even when the sprite is shown small "
        "(a bold chibi expression). Transparent background, no text."
    )
    png = gen.with_retry(gen.edit, prompt, [base_frame(form)], "1024x1536", quality)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_bytes(png)
    return out


def cmd_gen(args) -> None:
    names = args.only.split(",") if args.only else list(EXPRESSIONS)
    failures = 0
    with cf.ThreadPoolExecutor(max_workers=args.jobs) as pool:
        futures = {pool.submit(_gen_one, args.form, n, args.quality): n for n in names}
        for future in cf.as_completed(futures):
            try:
                print("ok", future.result().relative_to(ROOT), flush=True)
            except Exception as error:
                failures += 1
                print("FAIL", futures[future], str(error)[:200], flush=True)
    print(f"完成，失败 {failures} 张")


def _mask(size: tuple[int, int], box: tuple[int, int, int, int], feather: int = 14) -> Image.Image:
    cx, cy, rx, ry = box
    mask = Image.new("L", size, 0)
    ImageDraw.Draw(mask).ellipse((cx - rx + feather, cy - ry + feather, cx + rx - feather, cy + ry - feather), fill=255)
    return mask.filter(ImageFilter.GaussianBlur(feather))


def _change_mask(base: Image.Image, variant: Image.Image, box: tuple[int, int, int, int]) -> Image.Image:
    """Face core plus every nearby pixel the new expression really changed.

    A fixed ellipse alone leaves ghosts where an eye corner or blush crosses its
    soft edge; adding the changed pixels (within a larger face area) takes the
    whole new feature instead of a half-blend.
    """
    cx, cy, rx, ry = box
    diff = ImageChops.difference(base.convert("RGB"), variant.convert("RGB")).convert("L")
    diff = diff.filter(ImageFilter.GaussianBlur(4)).point(lambda v: 255 if v > 22 else 0)
    limit = Image.new("L", base.size, 0)
    ImageDraw.Draw(limit).ellipse((cx - rx * 1.35, cy - ry * 1.45, cx + rx * 1.35, cy + ry * 1.35), fill=255)
    changed = ImageChops.multiply(diff, limit).filter(ImageFilter.MaxFilter(9))
    core = Image.new("L", base.size, 0)
    ImageDraw.Draw(core).ellipse((cx - rx * 0.8, cy - ry * 0.8, cx + rx * 0.8, cy + ry * 0.8), fill=255)
    return ImageChops.lighter(core, changed).filter(ImageFilter.GaussianBlur(5))


def _align(base: Image.Image, variant: Image.Image, box: tuple[int, int, int, int], search: int = 24) -> tuple[int, int, float]:
    """Find the (dx, dy) that best lines the variant's head up with the base.

    Compares a ring around the face (hair and outline that should NOT change),
    so the new expression itself does not bias the match.
    """
    cx, cy, rx, ry = box
    pad = 40
    region = (cx - rx - pad, cy - ry - pad, cx + rx + pad, cy + ry + pad)
    scale = 4
    ring = Image.new("L", (base.width, base.height), 0)
    d = ImageDraw.Draw(ring)
    d.rectangle(region, fill=255)
    d.ellipse((cx - rx, cy - ry, cx + rx, cy + ry), fill=0)
    small = lambda im: im.convert("L").resize((im.width // scale, im.height // scale))
    b, v, r = small(base), small(variant), ring.resize((base.width // scale, base.height // scale))
    rb = tuple(c // scale for c in region)
    best = (0, 0, float("inf"))
    s = search // scale
    for dy in range(-s, s + 1):
        for dx in range(-s, s + 1):
            shifted = ImageChops.offset(v, dx, dy)
            diff = ImageChops.difference(b.crop(rb), shifted.crop(rb))
            masked = ImageChops.multiply(diff, r.crop(rb))
            score = sum(masked.get_flattened_data()) / max(1, sum(r.crop(rb).get_flattened_data()) / 255)
            if score < best[2]:
                best = (dx * scale, dy * scale, score)
    return best


def composite(form: str, name: str) -> tuple[Path, tuple[int, int, float]]:
    base = Image.open(base_frame(form)).convert("RGBA")
    variant = Image.open(WORK / form / "expr" / "raw" / f"{name}.png").convert("RGBA")
    if variant.size != base.size:
        variant = variant.resize(base.size, Image.Resampling.LANCZOS)
    box = FACE_BOX[form]
    dx, dy, score = _align(base, variant, box)
    variant = ImageChops.offset(variant, dx, dy)
    out = base.copy()
    out.paste(variant, (0, 0), _change_mask(base, variant, box))
    # Never let the paste change the silhouette: keep the base alpha.
    out.putalpha(base.getchannel("A"))
    path = WORK / form / "expr" / "composite" / f"{name}.png"
    path.parent.mkdir(parents=True, exist_ok=True)
    out.save(path)
    return path, (dx, dy, score)


def cmd_composite(args) -> None:
    for name in EXPRESSIONS:
        if not (WORK / args.form / "expr" / "raw" / f"{name}.png").is_file():
            print("缺", name)
            continue
        path, (dx, dy, score) = composite(args.form, name)
        print(f"{name}: 偏移 ({dx},{dy}) 头部外圈差异 {score:.1f} → {path.relative_to(ROOT)}")


def cmd_install(args) -> None:
    """Crop and scale exactly like the idle frame, then add to the manifest."""
    form = args.form
    base = gen._clean_alpha(Image.open(base_frame(form)))
    bbox = base.getchannel("A").getbbox()
    manifest_path = ROOT / form / "manifests" / "actions.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    section: dict[str, dict] = {}
    for name in EXPRESSIONS:
        src = WORK / form / "expr" / "composite" / f"{name}.png"
        if not src.is_file():
            print("缺", name)
            continue
        crop = gen._clean_alpha(Image.open(src)).crop(bbox)
        frames = {}
        for h in HEIGHTS:
            w = max(1, round(crop.width * h / crop.height))
            rel = f"assets/processed/runtime/expressions/{name}_{h}.png"
            out = ROOT / form / "processed" / "runtime" / "expressions" / f"{name}_{h}.png"
            out.parent.mkdir(parents=True, exist_ok=True)
            crop.resize((w, h), Image.Resampling.LANCZOS).save(out, optimize=True)
            frames[str(h)] = [rel]
        section[name] = {"frames": frames}
    manifest["expressions"] = section
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"{form}：安装了 {len(section)} 个表情")


def cmd_sheet(_args) -> None:
    th = 260
    forms = list(FORMS)
    sheet = Image.new("RGB", (th * (len(EXPRESSIONS) + 1), th * len(forms)), (70, 80, 90))
    for r, form in enumerate(forms):
        cx, cy, rx, ry = FACE_BOX[form]
        region = (cx - rx - 60, cy - ry - 120, cx + rx + 60, cy + ry + 60)
        paths = [base_frame(form)] + [WORK / form / "expr" / "composite" / f"{n}.png" for n in EXPRESSIONS]
        for c, p in enumerate(paths):
            if not p.is_file():
                continue
            im = Image.open(p).convert("RGBA").crop(region)
            im.thumbnail((th, th))
            sheet.paste(im, (c * th, r * th), im)
    out = WORK / "expressions_sheet.png"
    sheet.save(out)
    print(out)


def main() -> None:
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except (AttributeError, ValueError):
        pass
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("gen"); p.add_argument("--form", choices=FORMS, required=True); p.add_argument("--only"); p.add_argument("--jobs", type=int, default=3); p.add_argument("--quality", default="medium")
    p = sub.add_parser("composite"); p.add_argument("--form", choices=FORMS, required=True)
    p = sub.add_parser("install"); p.add_argument("--form", choices=FORMS, required=True)
    sub.add_parser("sheet")
    args = parser.parse_args()
    {"gen": cmd_gen, "composite": cmd_composite, "install": cmd_install, "sheet": cmd_sheet}[args.cmd](args)


if __name__ == "__main__":
    main()
